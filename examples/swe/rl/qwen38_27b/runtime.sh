#!/usr/bin/env bash
# Source in every role. Submission pins shared source, profile, and artifact paths.
set -euo pipefail
export QWEN_ENV_FILE=${QWEN_SUBMITTED_ENV_FILE:-${QWEN_ENV_FILE:-}}
: "${QWEN_ENV_FILE:?Set the site profile}"
export QWEN_RUN_USER=${QWEN_RUN_USER:-${SUDO_USER:-$(id -un)}}
export QWEN_ENV_FILE
export QWEN_ARENA_TRIAL=${QWEN_SUBMITTED_TRIAL:-${QWEN_ARENA_TRIAL:-}}
set -a
source "$QWEN_ENV_FILE"
set +a
export QWEN_ARENA_TRIAL=${QWEN_SUBMITTED_TRIAL:-$QWEN_ARENA_TRIAL}
export QWEN_ENV_FILE=${QWEN_SUBMITTED_ENV_FILE:-$QWEN_ENV_FILE}
export USER="$QWEN_RUN_USER" LOGNAME="$QWEN_RUN_USER"
recipe_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
export QWEN_REPO=${QWEN_SUBMITTED_REPO:-${QWEN_REPO:-$(cd "$recipe_root/../../../.." && pwd)}}
export QWEN_RUN_DIR=${QWEN_SUBMITTED_RUN_DIR:-${QWEN_RUN_DIR:-}}
export QWEN_OUTPUT_ROOT=${QWEN_SUBMITTED_OUTPUT_ROOT:-${QWEN_OUTPUT_ROOT:-}}
export QWEN_RECIPE_DIR="$QWEN_REPO/examples/swe/rl/qwen38_27b"
export QWEN_RUNTIME_SCRIPT="$QWEN_RECIPE_DIR/runtime.sh"
export EXPERIMENT_ROOT=${QWEN_RUN_DIR:?Set an external run directory}
export QWEN_CONFIG="$EXPERIMENT_ROOT/train.yaml"
export QWEN_EXPERIMENT_NAME=${QWEN_EXPERIMENT_NAME:-sxj-qwen38-graybox19-rl}
export QWEN_ARENA_TRIAL=${QWEN_ARENA_TRIAL:?Set a short trial name}
for name in QWEN_MODEL QWEN_DENSE_RUNTIME AWEX_RUNTIME_ROOT \
  QWEN_ACTOR_IMAGE QWEN_ROLLOUT_IMAGE QWEN_OUTPUT_ROOT QWEN_PARTITION \
  QWEN_MOUNTS QWEN_CONTROLLER_MOUNTS QWEN_ACTOR_EXTRA_PYTHONPATH \
  QWEN_ROLLOUT_RUNTIME_DEPS QWEN_PROXY_DEPS MEGATRON_ROOT \
  ARENA_OPENAPI_BASE ARENA_OPENAPI_TOKEN ARENA_LLM_API_KEY \
  WANDB_BASE_URL WANDB_API_KEY; do
  : "${!name:?Set $name in the external site profile}"
  export "$name"
done
export QWEN_ARENA_OUTPUT="$QWEN_OUTPUT_ROOT"
export QWEN_RESERVATION=${QWEN_SUBMITTED_RESERVATION:-${QWEN_RESERVATION:-}}
export QWEN_NODELIST=${QWEN_SUBMITTED_NODELIST:-${QWEN_NODELIST:-}}
export QWEN_ACTOR_PYTHONPATH="$AWEX_RUNTIME_ROOT:$QWEN_RECIPE_DIR:$QWEN_REPO:$QWEN_DENSE_RUNTIME/dependencies:$QWEN_DENSE_RUNTIME/aweagent:$QWEN_ACTOR_EXTRA_PYTHONPATH"
export QWEN_ROLLOUT_PYTHONPATH="$AWEX_RUNTIME_ROOT:$QWEN_RECIPE_DIR:$QWEN_PROXY_DEPS:$QWEN_ROLLOUT_RUNTIME_DEPS:${QWEN_INFER_EXTRA_PYTHONPATH:+$QWEN_INFER_EXTRA_PYTHONPATH:}$QWEN_REPO:$MEGATRON_ROOT"
export QWEN_CONTROLLER_PYTHONPATH="$QWEN_ACTOR_PYTHONPATH"
export QWEN_ACTOR_LIBRARY_PATH="$QWEN_DENSE_RUNTIME/dependencies/nvidia/cudnn/lib:${LD_LIBRARY_PATH:-}"
case "${SLURM_JOB_NAME:-}" in
  *:rollout*)
    export PYTHONPATH="$QWEN_ROLLOUT_PYTHONPATH"
    export SGLANG_LOGGING_CONFIG_PATH="$QWEN_OUTPUT_ROOT/logs/$QWEN_RUN_USER/$QWEN_EXPERIMENT_NAME/$QWEN_ARENA_TRIAL/native/sglang-${SLURMD_NODENAME:-$(hostname)}-${SLURM_LOCALID:-0}.json"
    ;;
  *)
    export PYTHONPATH="$QWEN_ACTOR_PYTHONPATH"
    export LD_LIBRARY_PATH="$QWEN_ACTOR_LIBRARY_PATH"
    export CUDNN_PATH="$QWEN_DENSE_RUNTIME/dependencies/nvidia/cudnn"
    ;;
esac
export NO_PROXY='*' no_proxy='*'
export PYTHONDONTWRITEBYTECODE=1 HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1
export XDG_CACHE_HOME="${TMPDIR:-/tmp}/areal-q27-${SLURM_JOB_ID:-local}-${SLURM_LOCALID:-0}/cache"
mkdir -p "$XDG_CACHE_HOME"
unset QWEN_AWEX_FROZEN_CONTRACT MCORE_BRIDGE_ROOT
unset QWEN_QSA_STABLE_TOPK QWEN_ISOLATE_REQUEST_CACHE NCCL_ALGO NCCL_PROTO CUBLAS_WORKSPACE_CONFIG
unset QWEN_BATCH_REPLAY_PATH QWEN_BATCH_REPLAY_PATHS QWEN_BATCH_SNAPSHOT_DIR
unset QWEN_ARENA_TASK_IDS_FILE QWEN_ARENA_STREAMS_FILE
export QWEN_PLE_CHUNK_TOKENS=0 QWEN_GDN_CP_COMPAT=0
for runtime_file in "$QWEN_MODEL/config.json" "$AWEX_RUNTIME_ROOT/awex/models/qwen3_5.py" "$QWEN_DENSE_RUNTIME/dependencies/megatron/bridge/models/qwen_vl/qwen35_vl_bridge.py"; do
  test -f "$runtime_file"
done
unset recipe_root runtime_file name

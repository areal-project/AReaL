#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)

EXPERIMENT_NAME=${EXPERIMENT_NAME:-rl-perf-trace}
TRIAL_NAME=${TRIAL_NAME:-e2e-$(date +%Y%m%d-%H%M%S)}
MODEL_PATH=${MODEL_PATH:-Qwen/Qwen2.5-1.5B-Instruct}
N_GPUS_PER_NODE=${N_GPUS_PER_NODE:-8}
ACTOR_BACKEND=${ACTOR_BACKEND:-fsdp:d4p1t1}
ROLLOUT_BACKEND=${ROLLOUT_BACKEND:-sglang:d4p1t1}
TRAIN_BATCH_SIZE=${TRAIN_BATCH_SIZE:-16}
N_SAMPLES=${N_SAMPLES:-2}
TOTAL_TRAIN_STEPS=${TOTAL_TRAIN_STEPS:-6}
PROFILE_STEPS=${PROFILE_STEPS:-'[1,3]'}

export EXPERIMENT_NAME TRIAL_NAME MODEL_PATH N_GPUS_PER_NODE
export ACTOR_BACKEND ROLLOUT_BACKEND TRAIN_BATCH_SIZE N_SAMPLES
export TOTAL_TRAIN_STEPS PROFILE_STEPS

exec bash "$ROOT_DIR/examples/profile/run_rl_perf_trace_smoke.sh"

"""Internal AIS entrypoint: assemble Ray, then run the user's command on the head."""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import time
from collections.abc import Mapping
from pathlib import Path


def ais_role(env: Mapping[str, str]) -> str:
    """Use an explicit node rank, platform role, or the PTJob Pod name."""

    def role_for_rank(rank: str) -> str:
        if not re.fullmatch(r"[0-9]+", rank) or int(rank) >= int(
            env["AREAL_AIS_NODES"]
        ):
            raise ValueError(f"Invalid AIS node rank: {rank!r}")
        return "head" if int(rank) == 0 else "worker"

    if rank := env.get("AREAL_NODE_RANK"):
        return role_for_rank(rank)
    for name in ("AISTUDIO_TASK_ROLE_NAME", "PAI_CURRENT_TASK_ROLE_NAME"):
        role = env.get(name, "").lower()
        if role in ("master", "head", "chief"):
            return "head"
        if role == "worker":
            return "worker"
    pod = env.get("POD_NAME") or env.get("HOSTNAME", "")
    if re.search(r"(?:^|-)master-0$", pod):
        return "head"
    if re.search(r"(?:^|-)worker-[0-9]+$", pod):
        return "worker"
    if rank := env.get("RANK") or env.get("OMPI_COMM_WORLD_RANK"):
        return role_for_rank(rank)
    raise ValueError("Cannot identify this AIS Pod as master or worker.")


def rendezvous_path(root: Path, storage: Path, job_name: str) -> Path:
    if not re.fullmatch(r"areal-[0-9a-f]+", job_name):
        raise ValueError("Expected the unique job name generated by submit.py.")
    if not root.is_absolute() or not root.resolve().is_relative_to(storage.resolve()):
        raise ValueError(
            f"The Ray rendezvous root must be an absolute path under {storage}."
        )
    return root / ".ray-ais" / job_name / "head-address"


def publish_head(path: Path, address: str) -> None:
    # The per-submission directory must be new. A worker must never see a
    # partial address or connect to a stale head from an earlier attempt.
    path.parent.mkdir(parents=True, exist_ok=False)
    staging = path.with_suffix(".tmp")
    staging.write_text(address + "\n", encoding="utf-8")
    staging.replace(path)


def wait_for_head(path: Path, timeout: int) -> str:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            address = path.read_text(encoding="utf-8").strip()
        except FileNotFoundError:
            pass
        else:
            if address:
                return address
        time.sleep(1)
    raise TimeoutError(f"Timed out waiting for the AIS Ray head at {path}.")


def ready_for_training(
    nodes: list[dict], available_gpus: float, expected_nodes: int, gpus_per_node: int
) -> None:
    gpu_counts = [
        node["Resources"].get("GPU", 0)
        for node in nodes
        if node["Alive"] and node["Resources"].get("GPU", 0) > 0
    ]
    if len(gpu_counts) != expected_nodes or any(n != gpus_per_node for n in gpu_counts):
        raise RuntimeError(
            f"Expected {expected_nodes} × {gpus_per_node} GPUs; got {gpu_counts}."
        )
    if available_gpus < expected_nodes * gpus_per_node:
        raise RuntimeError(f"Only {available_gpus:g} Ray GPUs are available.")


def check_ais_devices(gpus_per_node: int, rdma: bool) -> None:
    import torch

    if rdma and not any(Path("/dev/infiniband").glob("uverbs*")):
        raise RuntimeError(
            "AIS was asked for RDMA, but this Pod has no RDMA verbs devices."
        )
    visible = torch.cuda.device_count()
    if visible != gpus_per_node:
        raise RuntimeError(f"Expected {gpus_per_node} GPUs in this Pod, got {visible}.")


def run_user_command(command: str, address: str) -> int:
    # Do not leak the PTJob's SPMD settings into a Ray driver.
    env = os.environ.copy()
    for key in (
        "AREAL_SPMD_MODE",
        "RANK",
        "LOCAL_RANK",
        "WORLD_SIZE",
        "MASTER_ADDR",
        "MASTER_PORT",
    ):
        env.pop(key, None)
    env["RAY_ADDRESS"] = address
    result = subprocess.run(("bash", "-c", command), env=env, check=False)
    return result.returncode if result.returncode >= 0 else 128 - result.returncode


def run_ais(command: str) -> int:
    # Match the validated bootstrap: Ray peers are on the private network.
    # Keep caller proxy settings intact for the command running on the head.
    caller_proxies = {k: os.environ.get(k) for k in ("NO_PROXY", "no_proxy")}
    os.environ.update(NO_PROXY="*", no_proxy="*")
    import ray

    from areal.api.cli_args import ClusterSpecConfig
    from areal.infra.launcher import ray_bootstrap as bootstrap

    n_nodes = int(os.environ["AREAL_AIS_NODES"])
    gpus = int(os.environ["AREAL_AIS_GPUS_PER_NODE"])
    cluster = ClusterSpecConfig(n_nodes=n_nodes, n_gpus_per_node=gpus)
    role = ais_role(os.environ)
    check_ais_devices(gpus, os.environ.get("AREAL_AIS_RDMA") == "1")
    path = rendezvous_path(
        Path(os.environ["AREAL_AIS_RAY_ROOT"]),
        Path(os.environ["AREAL_AIS_STORAGE_ROOT"]),
        os.environ["AREAL_AIS_JOB_NAME"],
    )
    node_ip = bootstrap.detect_node_ip()
    port = cluster.ray_port
    timeout = cluster.ray_bootstrap_timeout_seconds
    os.environ.pop("RAY_ADDRESS", None)
    if role == "worker":
        os.environ["AREAL_MASTER_ADDR"] = wait_for_head(path, timeout)
        bootstrap.bootstrap_worker(node_ip, gpus, ray_port=port, wait_timeout=timeout)
        return 0

    publish_head(path, node_ip)
    try:
        bootstrap.bootstrap_head(
            node_ip,
            n_nodes,
            gpus,
            ray_port=port,
            dashboard_port=cluster.ray_dashboard_port,
            wait_timeout=timeout,
        )
        ready_for_training(
            ray.nodes(), ray.available_resources().get("GPU", 0), n_nodes, gpus
        )
        print(f"Ray ready: {n_nodes} × {gpus} GPUs", flush=True)
        ray.shutdown()
        for key, value in caller_proxies.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
        return run_user_command(command, f"{node_ip}:{port}")
    finally:
        bootstrap.stop_local_ray()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("command", help="Shell command to run after Ray is ready")
    return run_ais(parser.parse_args().command)


if __name__ == "__main__":
    raise SystemExit(main())
